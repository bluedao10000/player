import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const root = fileURLToPath(new URL('public/', import.meta.url))
const files = (await readdir(root, { recursive: true })).filter(name => /\.(png|webp)$/.test(name)).sort()
const images = Object.fromEntries(await Promise.all(files.map(async (name) => [
  '/' + name, createHash('sha256').update(await readFile(join(root, name))).digest('hex'),
])))
const destination = new URL('src/lib/images.generated.ts', import.meta.url)
const source = '// Generated by generate-images.mjs.\nexport const bundledImages: Record<string, string> = ' +
  JSON.stringify(images, null, 2) + '\n'
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== source)
    throw new Error('Run node apps/web/generate-images.mjs to update the image inventory')
} else {
  await writeFile(destination, source)
}
