package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"log"
	"os"

	"anime-agent/api/internal/service/knowledge/chattools"
)

func main() {
	check := flag.Bool("check", false, "check the generated file without writing")
	output := flag.String("output", "../../packages/shared/knowledge-tools.generated.ts", "generated TypeScript path")
	flag.Parse()
	manifest, err := json.MarshalIndent(chattools.Manifest(), "", "  ")
	if err != nil {
		log.Fatal(err)
	}
	data := append([]byte("// Generated by npm run generate:knowledge-tools. Do not edit.\nexport const knowledgeTools = "), manifest...)
	data = append(data, []byte(" as const\n")...)
	if *check {
		found, err := os.ReadFile(*output)
		if err != nil || !bytes.Equal(found, data) {
			log.Fatal("knowledge tools manifest is out of date; run npm run generate:knowledge-tools")
		}
		return
	}
	if err := os.WriteFile(*output, data, 0644); err != nil {
		log.Fatal(err)
	}
}
